// Helper to generate standard 36-seat layout per bus
export function generateBusSeats(busNumber: string, basePrice: number): BusSeat[] {
  const seats: BusSeat[] = [];
  const rows = 9;
  const cols: ('A' | 'B' | 'C' | 'D')[] = ['A', 'B', 'C', 'D'];

  // Seeded deterministic randomness based on bus number
  const hash = busNumber.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);

  for (let r = 1; r <= rows; r++) {
    for (const c of cols) {
      const seatId = `${c}${r}`;
      let category: BusSeat['category'] = 'standard';
      if (c === 'A' || c === 'D') category = 'window';
      if (c === 'B' || c === 'C') category = 'aisle';
      if (r <= 2) category = 'women_elderly'; // Front 2 rows reserved for women/elderly
      if (r === 1) category = 'front_row';

      // Pre-book some seats to make it realistic
      const isBooked = ((hash * r + c.charCodeAt(0)) % 7 < 3);

      seats.push({
        id: seatId,
        row: r,
        col: c,
        category,
        priceBdt: category === 'front_row' ? basePrice + 5 : basePrice,
        isBooked,
      });
    }
  }

  return seats;
}

